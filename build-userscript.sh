#!/bin/zsh
# Regenerates twitch-timeline.user.js from the Safari extension's
# extension/content.js and content.css, so both share one source.
# Bump "version" in extension/manifest.json first: Tampermonkey only
# updates installed copies when @version goes up.
set -e
cd "$(dirname "$0")"
python3 - <<'EOF'
import json
version = json.load(open('extension/manifest.json'))['version']
css = open('extension/content.css').read()
js = open('extension/content.js').read()
raw = 'https://raw.githubusercontent.com/zex0s/twitch-timeline/main'
header = f'''// ==UserScript==
// @name         Twitch Timeline
// @namespace    https://github.com/zex0s/twitch-timeline
// @version      {version}
// @description  Rewind live Twitch streams: a timeline under the player, Skip to Live, and a "Chat is Live" notice.
// @author       zex0s
// @match        https://www.twitch.tv/*
// @icon         {raw}/extension/images/icon-64.png
// @require      https://cdn.jsdelivr.net/npm/hls.js@1.7.3/dist/hls.min.js
// @grant        none
// @run-at       document-idle
// @updateURL    {raw}/twitch-timeline.user.js
// @downloadURL  {raw}/twitch-timeline.user.js
// ==/UserScript==

// Generated by build-userscript.sh from extension/content.js and
// extension/content.css. Edit those, not this file.
'''
body = f"const style = document.createElement('style');\nstyle.textContent = {json.dumps(css)};\ndocument.head.append(style);\n\n{js}"
open('twitch-timeline.user.js', 'w').write(header + '(() => {\n' + body + '})();\n')
print(f'twitch-timeline.user.js {version}')
EOF
